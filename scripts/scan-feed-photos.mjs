// Scan images/feed/ and generate js/feedPhotos.js
// Filename convention: owner_caption.ext  (e.g. ghost_雪山黎明.jpg, any_咖啡.png)
//   owner ∈ ghost | soap | gaz | price | any   (prefix before first underscore)
//   caption = rest of the name (underscores → spaces), used as the description the model writes from
// Usage: node scripts/scan-feed-photos.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT      = join(__dirname, '..');
const FEED_DIR  = join(ROOT, 'images', 'feed');
const OUT_FILE  = join(ROOT, 'js', 'feedPhotos.js');

const VALID_OWNERS = new Set(['ghost', 'soap', 'gaz', 'price', 'any']);
const IMG_EXT      = /\.(jpe?g|png|gif|webp|avif)$/i;

let files = [];
try {
  files = readdirSync(FEED_DIR).filter(f => IMG_EXT.test(f));
} catch (e) {
  console.error(`[scan-feed-photos] 读不到 ${FEED_DIR}:`, e.message);
  process.exit(1);
}

const pool = [];
const skipped = [];
for (const file of files.sort()) {
  const base = file.replace(IMG_EXT, '');
  const us   = base.indexOf('_');
  const owner = us > 0 ? base.slice(0, us).toLowerCase() : '';
  const caption = us > 0 ? base.slice(us + 1).replace(/_/g, ' ').trim() : '';
  if (!VALID_OWNERS.has(owner) || !caption) {
    skipped.push(file);
    continue;
  }
  pool.push({ file: `images/feed/${file}`, owner, caption });
}

const banner = `// AUTO-GENERATED by scripts/scan-feed-photos.mjs — do not edit by hand.
// 往 images/feed/ 里丢命名好的图（owner_描述.jpg），然后跑：node scripts/scan-feed-photos.mjs
// owner ∈ ghost | soap | gaz | price | any（any = 谁都能发）；文件名的描述部分就是给模型的配图素材。`;
const body = `const FEED_PHOTO_POOL = ${JSON.stringify(pool, null, 2)};\n\nif (typeof window !== 'undefined') window.FEED_PHOTO_POOL = FEED_PHOTO_POOL;\n`;
writeFileSync(OUT_FILE, `${banner}\n${body}`, 'utf8');

console.log(`[scan-feed-photos] 写出 ${pool.length} 张图 → js/feedPhotos.js`);
if (skipped.length) {
  console.warn(`[scan-feed-photos] 跳过 ${skipped.length} 个不合规命名（需 owner_描述.ext，owner 必须是 ghost/soap/gaz/price/any）:`);
  skipped.forEach(f => console.warn('  - ' + f));
}
