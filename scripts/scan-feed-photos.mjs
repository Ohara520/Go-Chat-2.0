// Scan images/feed/ and generate js/feedPhotos.js
// V2: Structured metadata with poster/subject/scene/perspective separation
// Reads MANIFEST.json for metadata, validates against actual files
// Usage: node scripts/scan-feed-photos.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT      = join(__dirname, '..');
const FEED_DIR  = join(ROOT, 'images', 'feed');
const MANIFEST  = join(FEED_DIR, 'MANIFEST.json');
const OUT_FILE  = join(ROOT, 'js', 'feedPhotos.js');

const VALID_POSTERS = new Set(['ghost', 'soap', 'gaz', 'price', 'any']);
const VALID_SUBJECTS = new Set([null, 'ghost', 'soap', 'gaz', 'price']);
const VALID_PERSPECTIVES = new Set(['first_person', 'third_person']);
const IMG_EXT = /\.(jpe?g|png|gif|webp|avif)$/i;

// Load manifest
let manifest = { photos: [] };
if (existsSync(MANIFEST)) {
  try {
    manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  } catch (e) {
    console.error(`[scan-feed-photos] Failed to parse MANIFEST.json:`, e.message);
    process.exit(1);
  }
}

// Collect all actual image files from subdirectories
const actualFiles = new Set();
for (const poster of ['ghost', 'soap', 'gaz', 'price', 'any']) {
  const dir = join(FEED_DIR, poster);
  if (!existsSync(dir)) continue;
  try {
    const files = readdirSync(dir).filter(f => IMG_EXT.test(f));
    files.forEach(f => actualFiles.add(`${poster}/${f}`));
  } catch (e) {
    console.warn(`[scan-feed-photos] Cannot read ${dir}:`, e.message);
  }
}

const pool = [];
const errors = [];
const warnings = [];

// Process each manifest entry
for (const entry of manifest.photos || []) {
  const { poster, subject, scene, perspective, file, caption } = entry;

  // Validate required fields
  if (!poster || !file || !caption) {
    errors.push(`Missing required fields in entry: ${JSON.stringify(entry)}`);
    continue;
  }

  // Validate poster
  if (!VALID_POSTERS.has(poster)) {
    errors.push(`Invalid poster "${poster}" in ${file} (must be: ghost, soap, gaz, price, any)`);
    continue;
  }

  // Validate subject (null is valid)
  if (subject !== undefined && subject !== null && !VALID_SUBJECTS.has(subject)) {
    errors.push(`Invalid subject "${subject}" in ${file} (must be: null, ghost, soap, gaz, price)`);
    continue;
  }

  // Validate perspective
  if (perspective && !VALID_PERSPECTIVES.has(perspective)) {
    errors.push(`Invalid perspective "${perspective}" in ${file} (must be: first_person, third_person)`);
    continue;
  }

  // Validate file exists
  const relPath = file.replace(/^images\/feed\//, '');
  if (!actualFiles.has(relPath)) {
    errors.push(`File not found: ${file} (expected at images/feed/${relPath})`);
    continue;
  }

  // Validate poster matches directory
  if (!relPath.startsWith(`${poster}/`)) {
    errors.push(`Poster mismatch: ${file} should be in ${poster}/ directory`);
    continue;
  }

  // Warn about subject === poster for third_person
  if (perspective === 'third_person' && subject === poster) {
    warnings.push(`Suspicious: ${file} has perspective=third_person but subject=poster (${poster})`);
  }

  // Add to pool
  pool.push({
    poster,
    subject: subject ?? null,
    scene: scene || null,
    perspective: perspective || null,
    file,
    caption
  });

  actualFiles.delete(relPath);
}

// Report orphaned files (files without manifest entries)
const orphaned = Array.from(actualFiles);

// Write output
const banner = `// AUTO-GENERATED by scripts/scan-feed-photos.mjs — do not edit by hand.
// Feed Photo Pool V2: structured metadata with poster/subject/scene/perspective
// Metadata lives in images/feed/MANIFEST.json; run this script to regenerate after changes.
// poster = who can post this photo | subject = who is IN the photo (null for environment/objects)
// scene = objective scene type | perspective = first_person (poster's view) or third_person (someone else in frame)
// caption = objective visual description, not a social media caption`;

const body = `const FEED_PHOTO_POOL = ${JSON.stringify(pool, null, 2)};\n\nif (typeof window !== 'undefined') window.FEED_PHOTO_POOL = FEED_PHOTO_POOL;\n`;

writeFileSync(OUT_FILE, `${banner}\n${body}`, 'utf8');

// Summary
console.log(`[scan-feed-photos] Generated ${pool.length} photos → js/feedPhotos.js`);

if (warnings.length) {
  console.warn(`\n⚠️  ${warnings.length} warning(s):`);
  warnings.forEach(w => console.warn('  - ' + w));
}

if (orphaned.length) {
  console.warn(`\n⚠️  ${orphaned.length} orphaned file(s) (in filesystem but not in MANIFEST.json):`);
  orphaned.forEach(f => console.warn('  - images/feed/' + f));
}

if (errors.length) {
  console.error(`\n❌ ${errors.length} error(s):`);
  errors.forEach(e => console.error('  - ' + e));
  process.exit(1);
}

console.log('✅ All validation passed.');
